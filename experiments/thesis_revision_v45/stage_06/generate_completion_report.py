"""Stage 6 — completion report generator.

Emits ``docs/thesis_revision_v45/stage_06/STAGE_06_COMPLETION_REPORT.md``.

Every count and measurement is read from the executed artefacts (the pilot results, the frozen
matrix, the run registry, the seed registry and the scenario definitions), so the report cannot
disagree with what was actually produced.

The few facts that only exist AFTER the commit — the commit SHA, the remote SHA and the GitHub
Actions run — are read from ``pilot/commit_record.json`` when present, and rendered as PENDING
otherwise.  That file is written by the Stage-6 commit procedure, never by hand.

Usage:
    python experiments/thesis_revision_v45/stage_06/generate_completion_report.py [--check]
"""
