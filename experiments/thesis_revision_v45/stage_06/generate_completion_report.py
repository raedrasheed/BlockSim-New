def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = build()
    target = DOCS / "STAGE_06_COMPLETION_REPORT.md"
    if args.check:
        if not target.exists() or target.read_bytes() != text.encode("utf-8"):
            print("FAIL: completion report differs from regeneration", file=sys.stderr)
            return 1
        print("OK: completion report is byte-identical to regeneration")
    else:
        target.write_text(text)
        print(f"wrote {target.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
