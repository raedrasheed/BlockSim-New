def accepted_modules_unchanged() -> bool:
    import hashlib
    return all(hashlib.sha256((REPO_ROOT / rel).read_bytes()).hexdigest() == d
               for rel, d in ACCEPTED_DIGESTS.items())


def build() -> str:
    S.assert_reference_matches_baseline()
    data = load_all()
    res = data["results"]
    t1 = [r for r in res if r["tier"] == "TIER1"]
